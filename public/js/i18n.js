const LANG_KEY = 'reacttr.lang';
let current = 'en';

function detect() {
  const fromUrl = new URLSearchParams(location.search).get('lang');
  if (fromUrl === 'en' || fromUrl === 'fa') return fromUrl;
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (saved === 'en' || saved === 'fa') return saved;
  } catch { /* storage unavailable */ }
  const nav = (navigator.languages && navigator.languages[0]) || navigator.language || 'en';
  return nav.toLowerCase().startsWith('fa') ? 'fa' : 'en';
}

export function initLang() {
  setLang(detect(), { persist: false });
  return current;
}

export function setLang(lang, { persist = true } = {}) {
  current = lang === 'fa' ? 'fa' : 'en';
  document.documentElement.lang = current;
  document.documentElement.dir = current === 'fa' ? 'rtl' : 'ltr';
  if (persist) {
    try { localStorage.setItem(LANG_KEY, current); } catch { /* ignore */ }
  }
}

export function lang() {
  return current;
}

function lookup(obj, key) {
  return key.split('.').reduce((o, k) => (o == null ? undefined : o[k]), obj);
}

/** Translate a UI key, e.g. t('home.title', { hl: '...' }). Numbers in vars are localized. */
export function t(key, vars) {
  let value = lookup(dict[current], key);
  if (value === undefined) value = lookup(dict.en, key);
  if (value === undefined) return key;
  if (typeof value !== 'string' || !vars) return value;
  return value.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? (typeof vars[k] === 'number' ? num(vars[k]) : vars[k]) : m));
}

/** Picks the current language from a { en, fa } content object. */
export function L(obj) {
  if (obj == null) return '';
  if (typeof obj === 'string') return obj;
  return obj[current] ?? obj.en ?? '';
}

/** The other language's value — used to show the alternate name under a title. */
export function other(obj) {
  if (!obj || typeof obj !== 'object') return '';
  return current === 'fa' ? obj.en : obj.fa;
}

const formatters = {};
export function num(n) {
  const loc = current === 'fa' ? 'fa-IR' : 'en-US';
  formatters[loc] = formatters[loc] || new Intl.NumberFormat(loc);
  return formatters[loc].format(n);
}
